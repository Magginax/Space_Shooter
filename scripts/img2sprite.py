"""Turns a picture already in the LCD palette into a shaded sprite for src/effects.

    python scripts/img2sprite.py <image> --crop L,T,R,B --rows N [--levels a,b,c]
                                 [--name NAME] [--out file.js] [--preview file.png]

Needs Pillow (pip install pillow). Steps: crop, downscale by area averaging to
`rows` high, map each cell's brightness to a level, keep only the biggest
connected piece (drops stray stars, bullets, beams), then mark the light cells
that the outside cannot reach as 'o' so the sprite hides what is behind it.

Levels, darkest first ('--levels' are the three brightness cut-offs, 0-255):
  '#' solid ink   ':' dither   '+' ghost   'o' light (inside)   '.' transparent

--preview writes the source crop and the sprite side by side at zoom 4.
The output is meant to be hand-cleaned afterwards; running again overwrites it.
"""
import argparse
from PIL import Image

INK = (19, 40, 11)
LCD = (166, 216, 92)


def to_sprite(image, crop, rows, levels):
    src = image.convert('L').crop(crop)
    cols = round(src.width * rows / src.height)
    small = src.resize((cols, rows), Image.BOX)
    lum = small.load()
    a, b, c = levels
    grid = [['#' if lum[x, y] < a else ':' if lum[x, y] < b else '+' if lum[x, y] < c else '.' for x in range(cols)] for y in range(rows)]

    # Keep the biggest 8-connected piece of ink.
    seen, best = set(), set()
    for y in range(rows):
        for x in range(cols):
            if grid[y][x] == '.' or (x, y) in seen:
                continue
            piece, stack = set(), [(x, y)]
            seen.add((x, y))
            while stack:
                px, py = stack.pop()
                piece.add((px, py))
                for dx in (-1, 0, 1):
                    for dy in (-1, 0, 1):
                        q = (px + dx, py + dy)
                        if 0 <= q[0] < cols and 0 <= q[1] < rows and q not in seen and grid[q[1]][q[0]] != '.':
                            seen.add(q)
                            stack.append(q)
            if len(piece) > len(best):
                best = piece
    for y in range(rows):
        for x in range(cols):
            if (x, y) not in best:
                grid[y][x] = '.'

    # Light cells the border cannot reach (4-connected) are inside the hull.
    outside = set()
    stack = [(x, y) for x in range(cols) for y in (0, rows - 1)] + [(x, y) for y in range(rows) for x in (0, cols - 1)]
    while stack:
        x, y = stack.pop()
        if not (0 <= x < cols and 0 <= y < rows) or (x, y) in outside or grid[y][x] != '.':
            continue
        outside.add((x, y))
        stack += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    for y in range(rows):
        for x in range(cols):
            if grid[y][x] == '.' and (x, y) not in outside:
                grid[y][x] = 'o'
    return [''.join(row) for row in grid], src


def render(sprite, zoom):
    """The sprite on the LCD the way ErrorScene draws it."""
    h, w = len(sprite), len(sprite[0])
    img = Image.new('RGB', (w * zoom, h * zoom), LCD)
    mix = lambda alpha: tuple(round(l + (i - l) * alpha) for i, l in zip(INK, LCD))
    for y, row in enumerate(sprite):
        for x, ch in enumerate(row):
            color = {'#': INK, ':': INK if (x + y) % 2 == 0 else None, '+': mix(0.3)}.get(ch)
            if color:
                img.paste(color, (x * zoom, y * zoom, (x + 1) * zoom, (y + 1) * zoom))
    return img


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('image')
    ap.add_argument('--crop', required=True, help='left,top,right,bottom in source pixels')
    ap.add_argument('--rows', type=int, required=True)
    ap.add_argument('--levels', default='90,130,165')
    ap.add_argument('--name', default='SPRITE')
    ap.add_argument('--out')
    ap.add_argument('--preview')
    args = ap.parse_args()

    crop = tuple(int(v) for v in args.crop.split(','))
    levels = tuple(int(v) for v in args.levels.split(','))
    assert len(crop) == 4 and len(levels) == 3 and levels[0] < levels[1] < levels[2], 'bad --crop or --levels'
    sprite, src = to_sprite(Image.open(args.image), crop, args.rows, levels)

    body = '\n'.join(f"  '{row}'," for row in sprite)
    js = (f'// Generated by scripts/img2sprite.py from {args.image.replace(chr(92), "/")}\n'
          f'// (crop {args.crop}, rows {args.rows}, levels {args.levels}), then cleaned by hand.\n'
          f"// '#' ink, ':' dither, '+' ghost, 'o' light, '.' nothing.\n"
          f'export const {args.name} = [\n{body}\n];\n')
    if args.out:
        open(args.out, 'w', encoding='utf-8', newline='\n').write(js)
    else:
        print(js)

    if args.preview:
        zoom = 4
        right = render(sprite, zoom)
        left = src.convert('RGB').resize((round(src.width * right.height / src.height), right.height), Image.LANCZOS)
        sheet = Image.new('RGB', (left.width + right.width + 8, right.height), (0, 0, 0))
        sheet.paste(left, (0, 0))
        sheet.paste(right, (left.width + 8, 0))
        sheet.save(args.preview)


if __name__ == '__main__':
    main()
